/**
 * Generates latency-sim.ts: a country-sized scope interface (560 methods,
 * realistic TSDoc, the four structural shapes in realistic proportions) so the
 * IDE/typecheck cost of the generated-interface design is measured before the
 * emitter exists. Run with:
 *
 *   node design/effects-probe/gen-latency-sim.ts
 */

import { writeFile } from "node:fs/promises";

const METHOD_COUNT = 560;
const PLANET_METHOD_COUNT = 30; // the median scope's effect count

function tsDoc(name: string, index: number): string {
  return [
    "  /**",
    `   * Simulated effect #${index}: stands in for a generated builder with the`,
    `   * usual two-line summary and a usage example.`,
    "   * ```",
    `   * ${name} = <value>`,
    "   * ```",
    "   */",
  ].join("\n");
}

function method(name: string, index: number, target: string): string {
  const doc = tsDoc(name, index);
  switch (index % 20) {
    case 0:
    case 1:
    case 2:
    case 3:
      return `${doc}\n  ${name}(): void;`;
    case 4:
    case 5:
    case 6:
    case 7:
    case 8:
      return `${doc}\n  ${name}(args: { amount?: number; type?: string; mult?: number }): void;`;
    case 9:
    case 10:
    case 11:
      return `${doc}\n  ${name}(args: { limit?: Trigger<"planet"> }, body: (planet: ${target}) => void): void;`;
    default:
      return `${doc}\n  ${name}(value: string | number): void;`;
  }
}

function interfaceFor(name: string, count: number, target: string): string {
  const methods = Array.from({ length: count }, (_, i) =>
    method(`simulatedEffect${name}${i}`, i, target)
  );
  return `export interface Big${name}Scope {\n${methods.join("\n\n")}\n}`;
}

const content = `// Generated by gen-latency-sim.ts. A measurement fixture, not API.
// ${METHOD_COUNT} methods simulate the country-sized generated scope interface.

import type { Trigger } from "../../src/trigger-core.ts";

${interfaceFor("Planet", PLANET_METHOD_COUNT, "BigPlanetScope")}

${interfaceFor("Country", METHOD_COUNT, "BigPlanetScope")}
`;

await writeFile(new URL("./latency-sim.ts", import.meta.url), content, "utf8");
console.log(`wrote latency-sim.ts with ${METHOD_COUNT}+${PLANET_METHOD_COUNT} methods`);
