/**
 * Every path this script touches is anchored to the module, not the process:
 * the inputs live in the repo, not in whatever directory `npm run codegen` was
 * invoked from, and a generator that silently reads a different rule set when
 * run from a subdirectory would be a nasty way to learn that.
 */
const ROOT = fileURLToPath(new URL("../../../", import.meta.url));
const VENDOR = path.join(ROOT, "vendor/cwtools-stellaris-config");
const CONFIG = path.join(VENDOR, "config");
/** The dump directory matching the game version these rules target. */
const DOCS = path.join(VENDOR, "script-docs/v4.4.1");
const OUT = path.join(ROOT, "packages/sdk/src/generated");
const BASELINE = fileURLToPath(new URL("./drift-baseline.json", import.meta.url));

function upstreamCommit(): string {
  const version = readFileSync(`${VENDOR}/VERSION.md`, "utf8");
  return /`([0-9a-f]{40})`/.exec(version)?.[1] ?? "unknown";
}

function header(commit: string, sources: readonly string[]): string {
  return (
    "// Generated by @pdx-ts/codegen-cwt. Do not edit.\n" +
    `// Source: cwtools-stellaris-config @ ${commit.slice(0, 12)}\n` +
    sources.map((source) => `// From: ${source}\n`).join("") +
    "\n"
  );
}

/**
 * Written through Prettier so the committed output matches the repo's style and
 * the pre-commit hook has nothing left to reformat — otherwise `lint-staged`
 * would rewrite these files and `codegen:check` would report a false diff.
 */
async function write(file: string, contents: string): Promise<void> {
  const target = path.join(OUT, file);
  const options = await resolveConfig(target);
  mkdirSync(OUT, { recursive: true });
  writeFileSync(target, await format(contents, { ...options, filepath: target }), "utf8");
}

function reportSection(title: string, lines: readonly string[]): void {
  if (lines.length === 0) {
    return;
  }
  console.log(`\n${title} (${lines.length}):`);
  for (const line of lines) {
    console.log(`  ${line}`);
  }
}

function checkDrift(report: DriftReport, rebaseline: boolean): void {
  if (rebaseline) {
    writeFileSync(BASELINE, `${JSON.stringify(report, null, 2)}\n`, "utf8");
    console.log(`Rebaselined drift: ${BASELINE}`);
    return;
  }
  // A baseline written before a join existed reads as that join being empty,
  // so adding a join reports its entire current state as drift to review
  // instead of crashing on the missing field.
  const baseline = {
    links: { rulesOnly: [], docsOnly: [] },
    ...(JSON.parse(readFileSync(BASELINE, "utf8")) as Partial<DriftReport>),
  } as DriftReport;
  const differences = compareToBaseline(report, baseline);
  if (differences.length === 0) {
    return;
  }
  console.error("\nThe two rule sources drifted since the recorded baseline:\n");
  console.error(differences.join("\n"));
  console.error(
    "\nEach line is a trigger, effect, or annotation that exists in one source and not\n" +
      "the other, which means codegen would emit a wrong signature or silently skip it.\n" +
      "Review the change, then re-run with --rebaseline to accept it."
  );
  process.exit(1);
}

async function main(): Promise<void> {
  const rebaseline = process.argv.includes("--rebaseline");
  const commit = upstreamCommit();

  const rules = loadRules(CONFIG);
  const docs = parseTriggerDocs(
    readFileSync(`${DOCS}/triggers.log`, "utf8"),
    readFileSync(`${DOCS}/effects.log`, "utf8")
  );
  const links = parseScopeLinks(readFileSync(`${DOCS}/scopes.log`, "utf8"));
  const modifierDocs = parseModifierDocs(readFileSync(`${DOCS}/modifiers.log`, "utf8"));

  checkDrift(reconcile(rules, docs, modifierDocs, links), rebaseline);

  const emitter = new Emitter(rules);
  const index = scopeIndex(rules);
  emitter.beginFile();
  const triggers = emitTriggers(emitter, docs.triggers, index);
  const triggerUsage = emitter.endFile();

  const dumpLinks = new Map(links.map((link) => [link.name, link]));
  const classifiedLinks = classifyLinks(emitter, dumpLinks, index);
  // The hand exports of src/triggers.ts share the links file's export
  // namespace through its `export *`, so they count as taken names too.
  const triggerLinks = emitTriggerLinks(
    classifiedLinks,
    index,
    new Set([...triggers.names, "trigger", "and", "or", "not", "nand", "nor", "target"])
  );

  emitter.beginFile();
  const effects = emitEffects(emitter, docs.effects, index, classifiedLinks.links);
  const effectUsage = emitter.endFile();

  const contents: Array<{
    manifest: (typeof CONTENT_MANIFEST)[number];
    /** Registry name: the CWT type unless the manifest renames it via `as`. */
    registry: string;
    /** The CWT reference this registry's definitions satisfy. */
    referenceName: string;
    /** Top-level keyword, for registries CWT marks with `name_field`. */
    keyword: string | undefined;
    type: ContentType;
    emission: ContentEmission;
    usage: ReturnType<Emitter["endFile"]>;
  }> = [];
  for (const manifest of CONTENT_MANIFEST) {
    const type = rules.contentTypes.get(manifest.type);
    const body = rules.bodies.get(manifest.type);
    if (type === undefined || body === undefined) {
      throw new Error(`${manifest.source} no longer declares type[${manifest.type}] and its body`);
    }
    const entry: ContentManifestEntry = manifest;
    const registry = entry.as ?? entry.type;
    const keyword = entry.keyword;
    // A keyword the rules do declare must match what the manifest claims;
    // silence here would emit a top-level key the game quietly ignores.
    if (keyword !== undefined && type.nameField === null) {
      throw new Error(`type[${manifest.type}] declares no name_field, so it has no keyword`);
    }
    if (keyword === undefined && type.nameField !== null) {
      throw new Error(
        `type[${manifest.type}] declares name_field=${type.nameField}, so the manifest ` +
          "entry needs the keyword its entries are written under"
      );
    }
    // A negated filter says which key the entries are *not* written under, so
    // it constrains nothing about the keyword and cannot contradict it.
    if (
      type.keyFilter !== null &&
      !type.keyFilter.negated &&
      keyword !== undefined &&
      keyword !== type.keyFilter.key
    ) {
      throw new Error(
        `type[${manifest.type}] declares ## type_key_filter = ${type.keyFilter.key} but the ` +
          `manifest claims keyword ${keyword}`
      );
    }
    emitter.beginFile();
    const emission = emitContentType(emitter, type, body, registry);
    const usage = emitter.endFile();
    contents.push({
      manifest,
      registry,
      referenceName: referenceNameOf(entry, type),
      keyword,
      type,
      emission,
      usage,
    });
  }

  // An alias category emitted as its own shared module, from either of the two
  // reasons a category needs one: an overlay row lowering a *keyed* field onto
  // it (`civic_or_origin.potential` -> `government_trigger`), or a body
  // splicing it unkeyed (`solar_system_initializer` -> `planet_initializer`).
  // Both produce a named interface plus a `registerAliasStructFields` call, so
  // they share a write loop and a report line.
  //
  // A worklist rather than a flat list, because a spliced category can splice
  // further categories: `planet_initializer` reaches `moon_initializer`, which
  // reaches itself. Runs after the content loop so the splice seeds exist.
  const aliasCategories = new Map<
    string,
    {
      readonly code: string;
      readonly typeName: string;
      readonly usage: Usage;
      readonly emittedMembers: readonly string[];
      readonly declinedMembers: readonly string[];
    }
  >();
  const aliasSplices = new Map<string, AliasSpliceEmission>();
  const emitCategory = (category: string, kind: "struct" | "splice"): void => {
    if (aliasCategories.has(category)) {
      return;
    }
    if (kind === "struct") {
      // An overlay row naming a category the rules do not declare is a
      // mistake in the row, so this throws rather than emitting nothing.
      const members = rules.aliasCategories.get(category);
      if (members === undefined || members.size === 0) {
        throw new Error(
          `overlay requests aliasStruct category "${category}" but the rules declare no ` +
            `alias[${category}:...] members — add it to EXTRA_ALIAS_CATEGORIES`
        );
      }
      emitter.beginFile();
      const emission = emitAliasStruct(emitter, category, members);
      aliasCategories.set(category, { ...emission, usage: emitter.endFile() });
      return;
    }
    // A splice seed is different: not every spliced category is structural, and
    // a non-structural one is not an error. `static_modifier` splices
    // `modifier`, whose authoring member is the `ModifierClosure` the runtime
    // already knows and whose members the rules keep outside `aliasCategories`
    // entirely — so there is no interface and no field table to emit.
    if (structuralSpliceOf(emitter, category) === null) {
      return;
    }
    emitter.beginFile();
    const emission = emitAliasSplice(emitter, category)!;
    const usage = emitter.endFile();
    aliasSplices.set(category, emission);
    aliasCategories.set(category, {
      code: emission.code,
      typeName: emission.typeName,
      usage,
      emittedMembers: emission.emittedFields.map((field) => field.field),
      declinedMembers: [...emission.declinedFields, ...emission.unsupported],
    });
    for (const nested of emission.spliceCategories) {
      emitCategory(nested, "splice");
    }
  };
  for (const override of [
    ...CONTENT_FIELD_OVERRIDES.values(),
    ...REPEATED_STRUCT_FIELD_OVERRIDES.values(),
  ]) {
    if (override.shape === "aliasStruct") {
      emitCategory(override.category!, "struct");
    }
  }
  for (const content of contents) {
    for (const category of content.emission.inlineSplices) {
      emitCategory(category, "splice");
    }
  }

  // Registers every ref this namespace names (including the ref-only extras —
  // sound, sound_effect, sprite, resource) with `emitter.usedRefs` before
  // `refs.ts` is written below, so their `XRef` aliases survive even if
  // nothing else in the rules happens to reference them.
  const vanillaRefs = emitVanillaRefs(
    emitter,
    CONTENT_MANIFEST,
    VANILLA_REF_EXTRAS,
    new Map(contents.map((content) => [content.registry, content.referenceName]))
  );

  await write(
    "scopes.ts",
    header(commit, ["scopes.cwt"]) + emitScopes(canonicalScopes(rules.scopes))
  );
  await write(
    "refs.ts",
    header(commit, ["type references across the rule files"]) + emitRefs(emitter)
  );
  await write("enums.ts", header(commit, ["enums.cwt"]) + emitEnums(emitter));
  await write(
    "value-sets.ts",
    header(commit, ["value sets referenced across the rule files"]) + emitValueSets(emitter)
  );
  const modifiers = emitModifiers(
    joinModifierScopes(rules, modifierDocs, (token) => emitter.canonicalScope(token))
  );
  await write(
    "modifiers.ts",
    header(commit, ["script-docs/v4.4.1/modifiers.log", "modifier_categories.cwt"]) +
      'import type { CustomModifiers } from "../content.ts";\n' +
      'import type { ScopeName } from "./scopes.ts";\n\n' +
      modifiers.code
  );
  // `Trigger` and `ScriptValue` both live in `trigger-core.ts`, so one clause
  // covers both — `Trigger<` stays a substring match (already precise; see
  // `GovernmentTriggerBlock`, which a bare "Trigger" match would false-hit),
  // `ScriptValue` a word-boundary one since it has no such collision.
  const triggerCoreImports = (code: string): string => {
    const names = [
      ...(code.includes("Trigger<") ? ["Trigger"] : []),
      ...(referencesIdentifier(code, "ScriptValue") ? ["ScriptValue"] : []),
    ];
    return names.length === 0
      ? ""
      : `import type { ${names.join(", ")} } from "../trigger-core.ts";\n`;
  };
  // A module referencing another alias category's interface needs both a type
  // import and a bare side-effect import: the type import is erased at build
  // time, and only the side effect guarantees that category's
  // `registerAliasStructFields` call has run before anything is serialized.
  // Categories reference each other (`planet_initializer` holds
  // `MoonInitializerFields`) and registries reference categories, so both write
  // loops resolve it the same way.
  const aliasCategoryImports = (code: string, self?: string): string =>
    [...aliasCategories]
      .filter(
        ([category, emission]) => category !== self && referencesIdentifier(code, emission.typeName)
      )
      .map(([category, emission]) => {
        const file = `./${category.replaceAll("_", "-")}.ts`;
        return (
          `import type { ${emission.typeName} } from ${JSON.stringify(file)};\n` +
          `import ${JSON.stringify(file)};\n`
        );
      })
      .join("");
  for (const [category, emission] of aliasCategories) {
    // `ContentField` is always used — every category emits a field table — and
    // the rest only when the category's own members reach for them. Matched on
    // `EffectBlock<`/`Trigger<` rather than the bare name, since `Trigger`
    // is a substring of `GovernmentTriggerBlock`.
    const runtimeTypes = ["ContentField", "EffectBlock<", "ModifierClosure"]
      .filter((name) =>
        name.endsWith("<")
          ? emission.code.includes(name)
          : referencesIdentifier(emission.code, name)
      )
      .map((name) => name.replace("<", ""));
    await write(
      `${category.replaceAll("_", "-")}.ts`,
      header(commit, [`alias[${category}:...] across the rule files`]) +
        `import { registerAliasStructFields, type ${runtimeTypes.join(", type ")} } ` +
        'from "../content.ts";\n' +
        triggerCoreImports(emission.code) +
        (emission.code.includes("ScopeName")
          ? 'import type { ScopeName } from "./scopes.ts";\n'
          : "") +
        importList(
          "./enums.ts",
          emission.usage.enums.map((name) => emitter.enumTypeName(name))
        ) +
        importList(
          "./refs.ts",
          emission.usage.refs.map((name) => emitter.refTypeName(name))
        ) +
        importList(
          "./value-sets.ts",
          emission.usage.valueSets.map((name) => emitter.valueSetTypeName(name))
        ) +
        // A category whose own interface is self-recursive imports nothing for
        // itself; `self` keeps it from importing its own module.
        aliasCategoryImports(emission.code, category) +
        "\n" +
        emission.code
    );
  }
  for (const content of contents) {
    const runtimeTypes = [
      "ContentField",
      "ContentLocalisation",
      "DefinedContent",
      "EconomicResourceBlock",
      "EconomicResourceBlockNoProduce",
      "EffectBlock",
      "ModifierBlock",
      "ModifierClosure",
      "TriggeredModifier",
      "WeightBlock",
      "WeightBlockWithLoc",
      "WithFrom",
    ].filter((name) => referencesIdentifier(content.emission.code, name));
    const aliasStructImports = aliasCategoryImports(content.emission.code);
    await write(
      `${content.registry.replaceAll("_", "-")}.ts`,
      header(commit, [content.manifest.source]) +
        importList("../content.ts", runtimeTypes) +
        triggerCoreImports(content.emission.code) +
        (content.emission.code.includes("ScopeName")
          ? 'import type { ScopeName } from "./scopes.ts";\n'
          : "") +
        importList(
          "./enums.ts",
          content.usage.enums.map((name) => emitter.enumTypeName(name))
        ) +
        importList(
          "./refs.ts",
          content.usage.refs.map((name) => emitter.refTypeName(name))
        ) +
        importList(
          "./value-sets.ts",
          content.usage.valueSets.map((name) => emitter.valueSetTypeName(name))
        ) +
        aliasStructImports +
        "\n" +
        content.emission.code
    );
  }
  const contentSources = CONTENT_MANIFEST.map((entry) => entry.source).filter(
    (source, index, sources) => sources.indexOf(source) === index
  );
  await write("content-registry.ts", header(commit, contentSources) + contentRegistry(contents));
  const definers = contentDefiners(contents);
  await write("content-definers.ts", header(commit, contentSources) + definers.code);
  await write(
    "vanilla-refs.ts",
    header(commit, [...contentSources, "content-manifest.ts (VANILLA_REF_EXTRAS)"]) +
      'import type { CheckedVanillaId, VanillaId, VanillaTrie } from "../vanilla-ids.ts";\n' +
      'import { makeIdTrie } from "../vanilla-trie.ts";\n' +
      importList(
        "./refs.ts",
        vanillaRefs.refs.map((name) => emitter.refTypeName(name))
      ) +
      "\n" +
      vanillaRefs.code
  );
  await write(
    "triggers.ts",
    header(commit, ["triggers.cwt", "aliases.cwt", "script-docs/v4.4.1/triggers.log"]) +
      'import { block, cmp, kv, type PdxEntry, type PdxOp } from "@pdx-ts/pdxscript";\n' +
      'import type { ContentRefUse } from "../content-refs.ts";\n' +
      `import { trigger, type Trigger${referencesIdentifier(triggers.code, "ScriptValue") ? ", type ScriptValue" : ""} } ` +
      'from "../trigger-core.ts";\n' +
      'import type { ScopeName } from "./scopes.ts";\n' +
      importList(
        "./enums.ts",
        triggerUsage.enums.map((name) => emitter.enumTypeName(name))
      ) +
      importList(
        "./refs.ts",
        triggerUsage.refs.map((name) => emitter.refTypeName(name))
      ) +
      importList(
        "./value-sets.ts",
        triggerUsage.valueSets.map((name) => emitter.valueSetTypeName(name))
      ) +
      'import { refId } from "./refs.ts";\n\n' +
      triggers.code
  );
  await write(
    "links.ts",
    header(commit, ["links.cwt", "script-docs/v4.4.1/scopes.log"]) +
      'import { block } from "@pdx-ts/pdxscript";\n' +
      'import { trigger, type Trigger } from "../trigger-core.ts";\n' +
      'import type { ScopeName } from "./scopes.ts";\n\n' +
      triggerLinks.code
  );
  await write(
    "effects.ts",
    header(commit, [
      "effects.cwt",
      "aliases.cwt",
      "links.cwt",
      "script-docs/v4.4.1/effects.log",
      "script-docs/v4.4.1/scopes.log",
    ]) +
      'import type { PdxOp } from "@pdx-ts/pdxscript";\n' +
      'import type { Modifier, StructuralEffects } from "../effect-core.ts";\n' +
      `import type { Trigger${referencesIdentifier(effects.interfaces, "ScriptValue") ? ", ScriptValue" : ""} } ` +
      'from "../trigger-core.ts";\n' +
      'import type { ScopeName } from "./scopes.ts";\n' +
      importList(
        "./enums.ts",
        effectUsage.enums.map((name) => emitter.enumTypeName(name))
      ) +
      importList(
        "./refs.ts",
        effectUsage.refs.map((name) => emitter.refTypeName(name))
      ) +
      importList(
        "./value-sets.ts",
        effectUsage.valueSets.map((name) => emitter.valueSetTypeName(name))
      ) +
      "\n" +
      effects.interfaces
  );
  await write(
    "effect-meta.ts",
    header(commit, ["effects.cwt", "aliases.cwt", "links.cwt"]) + effects.meta
  );
  const events = emitEvents(emitter);
  await write(
    "events.ts",
    header(commit, ["events/events.cwt"]) +
      'import type { ScopeName } from "./scopes.ts";\n\n' +
      events.code
  );
  await write(
    "event-definers.ts",
    header(commit, ["events/events.cwt"]) +
      'import { buildEvent, type EventDef } from "../events.ts";\n' +
      'import { assertNamespace } from "../items.ts";\n' +
      'import type { EventItem } from "../items.ts";\n' +
      'import { EVENT_KINDS, type EventKindKey } from "./events.ts";\n' +
      'import type { ScopeName } from "./scopes.ts";\n\n' +
      events.definerCode
  );
  await write(
    "event-fires.ts",
    header(commit, ["events/events.cwt", "effects.cwt"]) +
      'import type { FireEventArgs, WitnessedFireEventArgs } from "../events.ts";\n' +
      'import type { ScopeName } from "./scopes.ts";\n\n' +
      events.firesCode
  );
  const onActions = emitOnActions(rules);
  await write("on-actions.ts", header(commit, ["on_actions.cwt"]) + onActions.code);

  console.log(`cwtools-stellaris-config @ ${commit.slice(0, 12)}`);
  console.log(
    `\nscopes: ${canonicalScopes(rules.scopes).length}` +
      ` | enums emitted: ${emitter.usedEnums.size}` +
      ` | refs emitted: ${emitter.usedRefs.size}` +
      ` | value sets emitted: ${emitter.usedValueSets.size}`
  );
  console.log(
    `scope links: ${triggerLinks.emitted} trigger fns, ${effects.linkEmitted} effect methods` +
      ` emitted of ${rules.links.size} declared`
  );
  console.log(
    `modifiers: ${modifiers.names} names emitted` +
      ` (${modifiers.universal} universal, ${modifiers.groups} scope-set groups,` +
      ` ${modifiers.scopes} scopes, ${modifiers.trieTypes} path types;` +
      ` ${rules.modifierTemplates.length} cwt template rows)`
  );
  console.log(
    `triggers: ${triggers.emitted} emitted of ${rules.triggers.size} declared` +
      ` (${[...triggers.byShape].map(([kind, n]) => `${kind} ${n}`).join(", ")})`
  );
  console.log(
    `effects: ${effects.emitted} emitted of ${rules.effects.size} declared` +
      ` (${[...effects.byShape].map(([kind, n]) => `${kind} ${n}`).join(", ")}` +
      `; clusters ${effects.clusterCount})`
  );
  for (const content of contents) {
    console.log(`${content.registry}: ${content.emission.emittedFields.length} fields emitted`);
  }
  console.log(
    `content definers: ${definers.definers} emitted` +
      ` (${CONTENT_PATCH_REGISTRIES.size} free patchX,` +
      ` ${CONTENT_CONTRIBUTION_SINKS.size} free contribution adder,` +
      ` ${definers.grafted.length} re-exported from a hand-written graft)`
  );
  console.log(
    `vanilla refs: ${vanillaRefs.checked} checked constructors,` +
      ` ${vanillaRefs.tries} tries emitted (${vanillaRefs.refs.length} ref types registered)`
  );
  console.log(
    `event kinds: ${events.kinds} (${events.definers} definers, ` +
      `${events.fireMethods} typed fire methods)`
  );
  console.log(
    `on-actions: ${onActions.emitted} emitted (${onActions.noScope} scopeless and currently rejected)`
  );
  for (const [category, emission] of aliasCategories) {
    // The two kinds count different things, so they say different things. A
    // struct category lowers the category's own members, and the interesting
    // number is how many of them survived. A splice category has exactly one
    // member by construction; what it lowers is the fields *inside* that
    // member's block, so "of 1 declared" would be true and useless.
    const splice = aliasSplices.get(category);
    console.log(
      splice === undefined
        ? `${category}: ${emission.emittedMembers.length} alias-struct members emitted` +
            ` of ${rules.aliasCategories.get(category)?.size ?? 0} declared`
        : `${category}: ${emission.emittedMembers.length} fields emitted into ` +
            `${splice.typeName}, spliced as \`${splice.memberKey}\``
    );
    reportSection(`${category} members declined`, emission.declinedMembers);
  }

  reportSection("Triggers not emitted", summarise(triggers.skipped));
  reportSection("Effects not emitted", summarise(effects.skipped));
  reportSection(
    "Scope links not emitted",
    classifiedLinks.skipped.map((entry) => `${entry.name} — ${entry.reason}`)
  );
  reportSection("Effects emitted scalar-only (block overload dropped)", effects.scalarOnly);
  reportSection("On-actions not emitted", onActions.skipped);
  reportSection(
    "Event kinds without full typing",
    events.skipped.map((entry) => `${entry.name} — ${entry.reason}`)
  );
  reportSection("Enums widened to string (rules declare no values)", valuelessEnums(emitter));
  reportSection("Content definers taken from the hand-written grafts", definers.grafted);
  for (const content of contents) {
    const type = content.registry;
    console.log(`\n${type}: ${content.emission.emittedFields.length} fields emitted`);
    reportSection(`${type} fields declined`, content.emission.declinedFields);
    reportSection(
      `${type} alias categories spliced unkeyed at the top level`,
      content.emission.inlineSplices
    );
    reportSection(`${type} fields blocked on emitter machinery`, content.emission.machineryBacklog);
    reportSection(
      `${content.registry} fields the emitter could not lower`,
      content.emission.unsupported
    );
    reportSection(
      `${content.registry} localization aliases collapsed`,
      content.emission.localisationAliases
    );
  }
}

/**
 * One free definer per registry: the SDK-23 authoring surface, and the whole
 * content surface. A definition is a value a module exports; nothing is
 * registered at the definition site, because `collection(file, items)` and
 * `discoverContent` are what place it.
 *
 * The definers are literal-preserving (`<const Id extends string>`), so a
 * definition's id survives as its literal type all the way into the item the
 * definer returns — the property the deleted class methods, generic only in
 * the mod prefix, widened away.
 *
 * Three kinds of registry-specific member, each an overlay row rather than a
 * conditional in this emitter: `CONTENT_PATCH_REGISTRIES` adds a free `patchX`,
 * `CONTENT_CONTRIBUTION_SINKS` a free `addX` for the id-less sink, and
 * `HAND_WRITTEN_CONTENT_DEFINERS` replaces the mechanical `defineX` with a
 * re-export from `src/definers.ts`, so every definer this SDK has is importable
 * from this one module.
 *
 * The `XItem` union types are emitted here too: they describe what a collection
 * of this registry's items can hold.
 */
function contentDefiners(contents: readonly { registry: string; emission: ContentEmission }[]): {
  code: string;
  definers: number;
  grafted: string[];
} {
  const grafted: string[] = [];
  const runtimeItemTypes = new Set<string>(["ContentItem"]);
  const chunks: string[] = [];

  for (const content of contents) {
    const { registry, emission } = content;
    const name = emission.typeName;
    const key = JSON.stringify(registry);
    const spoken = registry.replaceAll("_", " ");
    const article = indefiniteArticle(spoken);
    const graft = HAND_WRITTEN_CONTENT_DEFINERS.get(registry);
    const patchable = CONTENT_PATCH_REGISTRIES.get(registry);
    const contribution = CONTENT_CONTRIBUTION_SINKS.get(registry);

    // A scope-parameterised registry erases S to `never`, not to its default:
    // `Trigger<S>` is contravariant, so `Def<Id, never>` is the supertype every
    // scoped variant satisfies, while `Def<Id, "planet">` would both exclude a
    // ship definition from this union and misreport its clauses as planet ones.
    const erased = emission.scopeParameter === null ? "" : "<string, never>";
    const itemArms = [`ContentItem<${key}, ${name}Def${erased}>`];
    if (patchable !== undefined) {
      itemArms.push(`${name}PatchItem`);
      runtimeItemTypes.add(`${name}PatchItem`);
    }
    if (contribution !== undefined) {
      itemArms.push("ContributionItem");
      runtimeItemTypes.add("ContributionItem");
    }

    const definitions: string[] = [];
    if (graft === undefined) {
      // A registry whose scopes are a property of the definition takes a second
      // type parameter and one extra authoring member. The member is stripped
      // before the def is stored: it is not a game key, and the returned item
      // erases S so a `"ship"` definition still belongs to this registry's item
      // union — `Trigger<S>` is contravariant, so a leaked S would make it not.
      const scoped = emission.scopeParameter;
      const parameters =
        scoped === null
          ? "<const Id extends string>"
          : `<\n  const Id extends string,\n  S extends ${scoped.typeName} = ` +
            `${JSON.stringify(scoped.fallback)},\n>`;
      const body =
        scoped === null
          ? `  return { itemKind: "content", type: ${key}, id: def.id, def };\n`
          : `  const { scope, ...rest } = def;\n` +
            `  return { itemKind: "content", type: ${key}, id: def.id, ` +
            `def: rest as ${name}Def<Id, never> };\n`;
      definitions.push(
        docComment([
          `Defines ${article} ${spoken} in this mod. The returned item is the`,
          "definition as a value and a reference to it; place it in a",
          "`collection(...)` — or export it from a discovered module — to emit it.",
          ...(scoped === null
            ? []
            : [
                "",
                "`scope` names which scope this definition's clauses run in and emits",
                `nothing; it defaults to \`${scoped.fallback}\`.`,
              ]),
        ]) +
          `export function define${name}${parameters}(\n` +
          `  def: ${name}Def<Id${scoped === null ? "" : ", S"}>\n` +
          `): ContentItem<${key}, ${name}Def<Id${scoped === null ? "" : ", never"}>> {\n` +
          body +
          "}\n"
      );
    } else {
      grafted.push(`${registry}.define${name} — ${graft.reason}`);
      definitions.push(
        `// define${name} is hand-written; re-exported here so every definer this\n` +
          "// SDK has comes from one module.\n" +
          `export { define${name} } from "../definers.ts";\n`
      );
    }
    if (patchable !== undefined) {
      definitions.push(
        docComment([
          `Patches ${article} vanilla ${spoken} as a whole-object override. The transform`,
          "runs here (pure); the duplicate-key and one-view checks stay in",
          "`buildMod`, which sees every patch together, and the emitted filename",
          "is always resolver-computed — a patch item never carries a file of its own.",
        ]) +
          `export function patch${name}<Source extends Parsed${name}>(\n` +
          `  ${camelCase(registry)}: Source,\n` +
          `  patch: (${camelCase(registry)}: Source) => ${name}Patch\n` +
          `): ${name}PatchItem {\n` +
          `  return { itemKind: "patch", patched: transform${name}(${camelCase(registry)}, patch) };\n` +
          "}\n"
      );
    }
    if (contribution !== undefined) {
      definitions.push(
        docComment([
          `Contributes to the shared additive \`default = { ${contribution.sink} = ... }\``,
          "sink: ids this mod names but does not own, with no author-named file.",
          "A ref listed twice is emitted once.",
        ]) +
          `export function ${contribution.method}(\n` +
          `  ${camelCase(contribution.sink)}: readonly (TypedRef<${JSON.stringify(contribution.refRegistry)}> | string)[]\n` +
          "): ContributionItem {\n" +
          "  return {\n" +
          '    itemKind: "contribution",\n' +
          `    registry: ${JSON.stringify(contribution.sink)},\n` +
          `    refRegistry: ${JSON.stringify(contribution.refRegistry)},\n` +
          `    ids: ${camelCase(contribution.sink)}.map((entry) => String(refId(entry))),\n` +
          "  };\n" +
          "}\n"
      );
    }

    chunks.push(
      docComment([`What ${article} ${spoken} collection can contain.`]) +
        `export type ${name}Item = ${itemArms.join(" | ")};\n\n` +
        definitions.join("\n")
    );
  }

  const patchNames = contents
    .filter((content) => CONTENT_PATCH_REGISTRIES.has(content.registry))
    .map((content) => content.emission.typeName);
  const refImports = contents.some((content) => CONTENT_CONTRIBUTION_SINKS.has(content.registry));
  const imports =
    importList("../items.ts", [...runtimeItemTypes]) +
    (refImports ? 'import { refId, type TypedRef } from "./refs.ts";\n' : "") +
    patchNames
      .map(
        (name) =>
          `import { patch${name} as transform${name}, type ${name}Patch } ` +
          'from "../vanilla/patch.ts";\n' +
          `import type { Parsed${name} } from "../vanilla/surface.ts";\n`
      )
      .join("") +
    contents
      .map((content) =>
        importList(`./${content.registry.replaceAll("_", "-")}.ts`, [
          `${content.emission.typeName}Def`,
          // A scope-parameterised definer constrains S by the registry's own
          // scope union, so that type has to travel with the Def.
          ...(content.emission.scopeParameter === null
            ? []
            : [content.emission.scopeParameter.typeName]),
        ])
      )
      .join("");

  return { code: imports + "\n" + chunks.join("\n"), definers: contents.length, grafted };
}

/**
 * The CWT reference a registry's definitions satisfy — what a field holding
 * `<component_template>` is actually asking for.
 *
 * The registry name answers this for every registry that is a whole CWT type.
 * An `as` rename is not: three registries share `type[component_template]`,
 * one per subtype, and the rules refer to them as
 * `<component_template.utility_component_template>`. Branding those with the
 * SDK's own registry name left a defined component template unable to reach
 * any field that references one — the name it carried was not a name the rules
 * have.
 *
 * `as` therefore has to be the subtype's own name, and codegen says so rather
 * than inventing a reference the rules would not recognise.
 */
function referenceNameOf(entry: ContentManifestEntry, type: ContentType): string {
  if (entry.as === undefined) {
    return type.name;
  }
  const subtype = type.subtypes.find((candidate) => candidate.name === entry.as);
  if (subtype === undefined) {
    const declared = type.subtypes.map((candidate) => candidate.name).join(", ");
    throw new Error(
      `The manifest renames type[${type.name}] to "${entry.as}", but that names no subtype ` +
        `of it, so the rules have no reference for the registry. Declared subtypes: ${declared}`
    );
  }
  return `${type.name}.${subtype.name}`;
}

function contentRegistry(
  contents: readonly {
    manifest: (typeof CONTENT_MANIFEST)[number];
    registry: string;
    referenceName: string;
    keyword: string | undefined;
    type: ContentType;
    emission: ContentEmission;
  }[]
): string {
  const imports = contents
    .map((content) => {
      const file = `./${content.registry.replaceAll("_", "-")}.ts`;
      const values = [content.emission.fieldsConstant, content.emission.localisationConstant];
      return `import { ${values.join(", ")} } from ${JSON.stringify(file)};\n`;
    })
    .join("");
  const descriptors = contents
    .map((content) => {
      const sourcePath = content.type.path;
      if (sourcePath === null || !sourcePath.startsWith("game/")) {
        throw new Error(`type[${content.registry}] has unusable path ${sourcePath}`);
      }
      const outputDir = sourcePath.slice("game/".length);
      const fileStem = path.posix.basename(outputDir);
      return (
        "  {\n" +
        `    type: ${JSON.stringify(content.registry)},\n` +
        `    referenceName: ${JSON.stringify(content.referenceName)},\n` +
        `    outputDir: ${JSON.stringify(outputDir)},\n` +
        `    fileStem: ${JSON.stringify(fileStem)},\n` +
        `    fields: ${content.emission.fieldsConstant},\n` +
        `    localisation: ${content.emission.localisationConstant},\n` +
        (content.keyword === undefined
          ? ""
          : `    keyedBy: { keyword: ${JSON.stringify(content.keyword)}, ` +
            `nameField: ${JSON.stringify(content.type.nameField)} },\n`) +
        "  },\n"
      );
    })
    .join("");
  return (
    'import type { ContentRegistryDescriptor } from "../content.ts";\n' +
    imports +
    "\n" +
    "export const CONTENT_REGISTRIES = [\n" +
    descriptors +
    "] as const satisfies readonly ContentRegistryDescriptor[];\n\n" +
    'export type ContentTypeName = (typeof CONTENT_REGISTRIES)[number]["type"];\n\n' +
    docComment([
      "The CWT reference a registry's definitions satisfy, as a type.",
      "",
      "The same thing `referenceName` carries as data, and the brand a",
      "`ContentItem` for that registry wears — which is what makes a defined",
      "component template reach a field holding `<component_template>`.",
    ]) +
    "export type ContentReferenceName<K extends ContentTypeName> = Extract<\n" +
    "  (typeof CONTENT_REGISTRIES)[number],\n" +
    "  { type: K }\n" +
    '>["referenceName"];\n'
  );
}

function importList(from: string, names: readonly string[]): string {
  if (names.length === 0) {
    return "";
  }
  return `import type { ${[...new Set(names)].sort().join(", ")} } from ${JSON.stringify(from)};\n`;
}

function summarise(skipped: readonly SkippedRule[]): string[] {
  const grouped = new Map<string, string[]>();
  for (const entry of skipped) {
    grouped.set(entry.reason, [...(grouped.get(entry.reason) ?? []), entry.name]);
  }
  return [...grouped]
    .sort((left, right) => right[1].length - left[1].length)
    .map(([reason, names]) => `${names.length} — ${reason}, e.g. ${names.slice(0, 3).join(", ")}`);
}

