/**
 * The win engine, exercised through the handoff's adversarial scenarios: a
 * synthetic vanilla whose last definer is `zz_zz_late.txt` (the computed
 * name must beat it or fail with the reason), the refusal path through the
 * rule table, and the stem-append lemma as a property rather than a belief.
 */

import { block, kv } from "@pdx-ts/pdxscript";
import fc from "fast-check";
import { describe, expect, it } from "vitest";

import { NoWinningFilenameError, PdxSdkError, UnverifiedRegistryError } from "../../src/errors.ts";
import { compareLogicalPaths, normalizeLogicalPath } from "../../src/resolver/path-order.ts";
import { planPatchEmission, type PatchInput } from "../../src/resolver/plan.ts";
import type { VanillaFile } from "../../src/vanilla/surface.ts";

function file(path: string, ...keys: string[]): VanillaFile {
  return { path: normalizeLogicalPath(path), sha256: "ab".repeat(32), keys };
}

function patch(key: string, sourceFile: string, locals?: Record<string, number>): PatchInput {
  return {
    key,
    sourceFile: normalizeLogicalPath(sourceFile),
    sourceSha256: "cd".repeat(32),
    entry: block(key, [kv("cost", 100), kv("area", "society")]),
    locals: new Map(Object.entries(locals ?? {})),
  };
}

const SOC = "common/technology/00_soc_tech.txt";

function plan(overrides: Partial<Parameters<typeof planPatchEmission>[0]> = {}) {
  return planPatchEmission({
    registry: "technologies",
    patches: [patch("tech_gene_tailoring", SOC)],
    enumeration: [file(SOC, "tech_gene_tailoring", "tech_other")],
    reservedPaths: [],
    prefix: "mymod",
    ...overrides,
  });
}

describe("the stem-append lemma", () => {
  it("appending to a stem always sorts after the stemmed file (property)", () => {
    const stem = fc.stringMatching(/^[a-zA-Z0-9_!.-]{1,40}$/);
    const suffix = fc.stringMatching(/^[a-z0-9_]{1,20}$/);
    fc.assert(
      fc.property(stem, suffix, (s, x) => {
        const source = normalizeLogicalPath(`dir/${s}.txt`);
        const appended = normalizeLogicalPath(`dir/${s}_${x}.txt`);
        expect(compareLogicalPaths(source, appended)).toBe(-1);
      }),
      { numRuns: 2000 }
    );
  });
});

describe("planPatchEmission", () => {
  it("computes the name off the last definer and names every file it beat", () => {
    const result = plan({
      enumeration: [
        file("common/technology/00_soc_tech.txt", "tech_gene_tailoring"),
        file("common/technology/00_strategic_resources_tech.txt", "tech_gene_tailoring"),
        file("common/technology/00_eng_tech.txt", "tech_other"),
      ],
    });
    expect(result.relPath).toBe("common/technology/00_strategic_resources_tech_mymod_patch.txt");
    expect(result.assertions).toEqual([
      {
        registry: "technologies",
        key: "tech_gene_tailoring",
        rule: "last-wins",
        confidence: "verified",
        beats: [
          "common/technology/00_soc_tech.txt",
          "common/technology/00_strategic_resources_tech.txt",
        ],
        verifiedAgainst: "4.4.6",
      },
    ]);
  });

  it("beats the adversarial zz_zz_late.txt", () => {
    const result = plan({
      enumeration: [
        file("common/technology/00_soc_tech.txt", "tech_gene_tailoring"),
        file("common/technology/zz_zz_late.txt", "tech_gene_tailoring"),
      ],
    });
    expect(result.relPath).toBe("common/technology/zz_zz_late_mymod_patch.txt");
  });

  it("emits a deterministic file with header, scope sentence, and hashes", () => {
    const result = plan();
    expect(result.content).toMatchInlineSnapshot(`
      "# Generated by @pdx-ts/sdk -- do not edit.
      # Overrides verified against Stellaris 4.4.6. Registry \`technologies\` is last-wins: this file byte-sorts after every file defining each key below.
      # Unverified against third-party mods (vanilla + this mod only).
      #   tech_gene_tailoring  beats common/technology/00_soc_tech.txt  source sha256 cdcdcdcdcdcd

      tech_gene_tailoring = {
      	cost = 100
      	area = society
      }
      "
    `);
    expect(plan().content).toBe(result.content);
  });

  it("one file per registry: the bar is the max across all patched keys", () => {
    const result = plan({
      patches: [patch("tech_a", SOC), patch("tech_b", "common/technology/10_late.txt")],
      enumeration: [file(SOC, "tech_a"), file("common/technology/10_late.txt", "tech_b")],
    });
    expect(result.relPath).toBe("common/technology/10_late_mymod_patch.txt");
    expect(result.assertions.map((a) => a.beats)).toEqual([
      ["common/technology/00_soc_tech.txt"],
      ["common/technology/10_late.txt"],
    ]);
  });

  it("escalates past a taken name and never emits at an enumerated path", () => {
    const result = plan({
      enumeration: [
        file(SOC, "tech_gene_tailoring"),
        file("common/technology/00_soc_tech_mymod_patch.txt", "tech_unrelated"),
      ],
    });
    expect(result.relPath).toBe("common/technology/00_soc_tech_mymod_patch_p.txt");
  });

  it("escalates past the mod's own reserved paths", () => {
    const result = plan({
      reservedPaths: ["common/technology/00_soc_tech_mymod_patch.txt"],
    });
    expect(result.relPath).toBe("common/technology/00_soc_tech_mymod_patch_p.txt");
  });

  it("refuses a non-ASCII last definer instead of guessing", () => {
    expect(() =>
      plan({
        enumeration: [file("common/technology/00_söc_tech.txt", "tech_gene_tailoring")],
      })
    ).toThrow(NoWinningFilenameError);
    expect(() =>
      plan({
        enumeration: [file("common/technology/00_söc_tech.txt", "tech_gene_tailoring")],
      })
    ).toThrow(/ASCII-only by policy/);
  });

  it("refuses when no winning name fits the filesystem limit", () => {
    const longStem = "z".repeat(195);
    const enumeration = [file(`common/technology/${longStem}.txt`, "tech_gene_tailoring")];
    expect(() => plan({ enumeration })).toThrow(NoWinningFilenameError);
    expect(() => plan({ enumeration })).toThrow(
      /leaves no winning name within the filesystem limit/
    );
  });

  it("refuses a registry whose duplicate-winner cell is refused, citing it", () => {
    const call = () =>
      plan({
        registry: "ship-components",
        enumeration: [file("common/component_templates/00_utilities.txt", "tech_gene_tailoring")],
      });
    expect(call).toThrow(UnverifiedRegistryError);
    expect(call).toThrow(/has no verified duplicate-winner rule/);
    expect(call).toThrow(/pinned to Stellaris 4\.4\.6/);
  });

  it("refuses a first-wins registry: before-first emission is a later slice", () => {
    const call = () =>
      plan({
        registry: "events",
        enumeration: [file("events/vanilla_events.txt", "tech_gene_tailoring")],
      });
    expect(call).toThrow(PdxSdkError);
    expect(call).toThrow(/before-first emission is not implemented in this slice/);
  });

  it("surfaces an assumed cell in the assertion and the file header", () => {
    const result = plan({
      registry: "megastructures",
      enumeration: [file("common/megastructures/00_mega.txt", "tech_gene_tailoring")],
    });
    expect(result.assertions[0]?.confidence).toBe("assumed");
    expect(result.content).toContain("# ASSUMED field-replacement rule: Jackson, 2026-07-31");
  });

  it("re-declares needed file-local variables ahead of the objects", () => {
    const result = plan({
      patches: [patch("tech_gene_tailoring", SOC, { "@pp_points": 2 })],
    });
    expect(result.content).toContain("\n@pp_points = 2\n\ntech_gene_tailoring = {");
  });

  it("refuses two patches needing one local name at different values", () => {
    const call = () =>
      plan({
        patches: [
          patch("tech_a", SOC, { "@pp_points": 2 }),
          patch("tech_b", "common/technology/10_late.txt", { "@pp_points": 3 }),
        ],
        enumeration: [file(SOC, "tech_a"), file("common/technology/10_late.txt", "tech_b")],
      });
    expect(call).toThrow(/both need file-local @pp_points/);
  });

  it("refuses a patch carrying inline math: its dependencies are invisible", () => {
    const withMath: PatchInput = {
      key: "tech_gene_tailoring",
      sourceFile: normalizeLogicalPath(SOC),
      sourceSha256: "cd".repeat(32),
      entry: block("tech_gene_tailoring", [
        { kind: "entry", key: "cost", op: "=", value: { kind: "math", source: "@[ x + 1 ]" } },
      ]),
      locals: new Map(),
    };
    expect(() => plan({ patches: [withMath] })).toThrow(/inline-math/);
  });

  it("hard-errors when no surviving file defines a patched key", () => {
    expect(() => plan({ enumeration: [file(SOC, "tech_other")] })).toThrow(
      /no surviving file defines "tech_gene_tailoring"/
    );
  });
});
