import { readdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { SCRIPT_REFERENCE_SCOPES } from "@pdx-ts/sdk/script-reference";

import { parseScopePageSource, type ScopePageSource } from "../src/scope-page-source.ts";
import { buildScopeReference } from "../src/scope-reference.ts";

const packageRoot = path.resolve(import.meta.dirname, "..");
const sourceDir = path.join(packageRoot, "content/scope-pages");
const outputDir = path.join(packageRoot, "content/docs/scopes-and-effects");
const metaPath = path.join(outputDir, "meta.json");
const marker = "{/* Generated by scripts/generate-scope-pages.ts. Do not edit. */}";
const reservedPages = new Set(["index.mdx", "effects.mdx"]);

function renderPage(fragment: ScopePageSource): string {
  const model = buildScopeReference(fragment.scope);
  return `---
title: ${JSON.stringify(fragment.title)}
description: ${JSON.stringify(
    `Generated methods, event kinds, and transitions for ${model.interfaceName}.`
  )}
scope: ${fragment.scope}
---

${marker}

import { EventFireMethods } from "@/components/EventFireMethods";
import { EventKinds } from "@/components/EventKinds";
import { ScopeEffects } from "@/components/ScopeEffects";
import { ScopeIdentity } from "@/components/ScopeIdentity";
import { ScopeTransitions } from "@/components/ScopeTransitions";
import { StructuralMethods } from "@/components/StructuralMethods";
import { buildScopeReference } from "@/src/scope-reference";

export const model = buildScopeReference(${JSON.stringify(fragment.scope)});

<ScopeIdentity model={model} />

${fragment.prose}

## Event kinds whose bodies run in this scope

<EventKinds rows={model.eventKinds} />

## Ordinary effects

<ScopeEffects universal={model.universalEffects} scopeSpecific={model.scopeEffects} />

## Structural and control-flow methods

<StructuralMethods rows={model.structuralMethods} />

## Event-fire methods

<EventFireMethods rows={model.eventFireMethods} />

## Outgoing scope transitions

<ScopeTransitions rows={model.transitions} />
`;
}

async function fragments(): Promise<readonly ScopePageSource[]> {
  const filenames = (await readdir(sourceDir)).filter((filename) => filename.endsWith(".md"));
  const scopes = filenames.map((filename) => filename.slice(0, -3));
  const known = new Set<string>(SCRIPT_REFERENCE_SCOPES);
  const missing = SCRIPT_REFERENCE_SCOPES.filter((scope) => !scopes.includes(scope));
  const unknown = scopes.filter((scope) => !known.has(scope)).sort();
  const errors = [
    ...(missing.length === 0 ? [] : [`Missing scope prose: ${missing.join(", ")}.`]),
    ...(unknown.length === 0 ? [] : [`Unknown scope prose: ${unknown.join(", ")}.`]),
  ];
  if (errors.length > 0) throw new Error(errors.join("\n"));

  return Promise.all(
    SCRIPT_REFERENCE_SCOPES.map(async (scope) =>
      parseScopePageSource(scope, await readFile(path.join(sourceDir, `${scope}.md`), "utf8"))
    )
  );
}

function meta(scopes: readonly string[]): string {
  return `${JSON.stringify(
    {
      title: "Scopes & Effects",
      pages: ["index", "effects", "---Scopes---", ...scopes],
    },
    null,
    2
  )}\n`;
}

async function checkOrWrite(check: boolean): Promise<void> {
  const inputs = await fragments();
  const expected = new Map(inputs.map((input) => [`${input.scope}.mdx`, renderPage(input)]));
  const currentFiles = (await readdir(outputDir)).filter(
    (filename) => filename.endsWith(".mdx") && !reservedPages.has(filename)
  );
  const unexpected = currentFiles.filter((filename) => !expected.has(filename));

  if (check) {
    const missing: string[] = [];
    const stale: string[] = [];
    for (const [filename, contents] of expected) {
      try {
        if ((await readFile(path.join(outputDir, filename), "utf8")) !== contents) {
          stale.push(filename.slice(0, -4));
        }
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
        missing.push(filename.slice(0, -4));
      }
    }
    const expectedMeta = meta(inputs.map((input) => input.scope));
    const currentMeta = await readFile(metaPath, "utf8");
    const errors = [
      ...(missing.length === 0 ? [] : [`Missing generated scope pages: ${missing.join(", ")}.`]),
      ...(stale.length === 0 ? [] : [`Stale generated scope pages: ${stale.join(", ")}.`]),
      ...(unexpected.length === 0
        ? []
        : [
            `Orphaned generated scope pages: ${unexpected.map((name) => name.slice(0, -4)).join(", ")}.`,
          ]),
      ...(currentMeta === expectedMeta ? [] : ["Scopes & Effects navigation metadata is stale."]),
    ];
    if (errors.length > 0) throw new Error(errors.join("\n"));
    return;
  }

  for (const filename of unexpected) {
    const target = path.join(outputDir, filename);
    if (!(await readFile(target, "utf8")).includes(marker)) {
      throw new Error(`Refusing to remove non-generated scope page "${filename}".`);
    }
    await unlink(target);
  }
  await Promise.all(
    [...expected].map(([filename, contents]) =>
      writeFile(path.join(outputDir, filename), contents, "utf8")
    )
  );
  await writeFile(metaPath, meta(inputs.map((input) => input.scope)), "utf8");
}

const args = process.argv.slice(2);
if (args.some((arg) => arg !== "--check")) {
  throw new Error(`Unknown argument: ${args.find((arg) => arg !== "--check")}.`);
}
await checkOrWrite(args.includes("--check"));
