import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const html = await readFile(
  new URL("../.next/server/app/reference/situations.html", import.meta.url),
  "utf8"
);

assert.doesNotMatch(html, /has no `\$` id placeholder/);
assert.match(html, /has no <code>\$<\/code> id placeholder/);
assert.doesNotMatch(html, /<id>/);
assert.match(html, /not a static &#x3C;id>-keyed slot/);

const scopeMarkdown = await readFile(
  new URL(
    "../.next/server/app/llms.mdx/scopes-and-effects/scopes/alliance/content.md.body",
    import.meta.url
  ),
  "utf8"
);
const scopeHtml = await readFile(
  new URL("../.next/server/app/scopes-and-effects/scopes/alliance.html", import.meta.url),
  "utf8"
);

for (const output of [scopeMarkdown, scopeHtml]) {
  assert.doesNotMatch(output, /Generated by scripts\/generate-scope-pages\.ts/);
  assert.doesNotMatch(output, /activateGateway/);
}
assert.match(scopeMarkdown, /universal effects\]\(\/scopes-and-effects\/effects\/\)/);
assert.match(scopeHtml, /href="\/scopes-and-effects\/effects\/"/);

const overviewHtml = await readFile(
  new URL("../.next/server/app/scopes-and-effects.html", import.meta.url),
  "utf8"
);
const effectsHtml = await readFile(
  new URL("../.next/server/app/scopes-and-effects/effects.html", import.meta.url),
  "utf8"
);
const effectsMarkdown = await readFile(
  new URL(
    "../.next/server/app/llms.mdx/scopes-and-effects/effects/content.md.body",
    import.meta.url
  ),
  "utf8"
);
const triggersHtml = await readFile(
  new URL("../.next/server/app/scopes-and-effects/triggers.html", import.meta.url),
  "utf8"
);
const triggersMarkdown = await readFile(
  new URL(
    "../.next/server/app/llms.mdx/scopes-and-effects/triggers/content.md.body",
    import.meta.url
  ),
  "utf8"
);
const countryHtml = await readFile(
  new URL("../.next/server/app/scopes-and-effects/scopes/country.html", import.meta.url),
  "utf8"
);
const armyHtml = await readFile(
  new URL("../.next/server/app/scopes-and-effects/scopes/army.html", import.meta.url),
  "utf8"
);

assert.match(overviewHtml, /<h1[^>]*>Overview<\/h1>/);
assert.match(effectsHtml, /<h1[^>]*>List of Effects<\/h1>/);
assert.match(triggersHtml, /<h1[^>]*>List of Triggers<\/h1>/);

assert.match(effectsHtml, /id="effects-abortSituation"/);
assert.doesNotMatch(effectsHtml, /id="effects-win"/);
assert.match(effectsHtml, /<summary[^>]*>/);
assert.match(effectsHtml, /id="effects-abortSituation-details"/);
assert.equal(effectsHtml.match(/Scope pages for universal methods/g)?.length, 1);
assert.match(effectsHtml, /Method or PDXScript key/);
assert.match(effectsHtml, /Legal on scope/);

// The browser view is paged, while the agent-facing Markdown representation
// carries the complete table. `win` is the last method alphabetically.
assert.match(effectsMarkdown, /#effects-addResource/);
assert.match(effectsMarkdown, /#effects-win/);

assert.match(triggersHtml, /id="triggers-acquiredSpecimenCount"/);
assert.doesNotMatch(triggersHtml, /id="triggers-numOwnedPlanets"/);
assert.equal(triggersHtml.match(/Scope pages for universal builders/g)?.length, 1);
assert.match(triggersHtml, /Method or PDXScript key/);
assert.match(triggersHtml, /Legal on scope/);
for (const builder of ["hasCountryFlag", "isAi", "numOwnedPlanets"]) {
  assert.match(triggersMarkdown, new RegExp(`#triggers-${builder}`));
}

assert.match(countryHtml, /href="\/scopes-and-effects\/effects\/#effects-countryEvent"/);
assert.match(countryHtml, /href="\/scopes-and-effects\/triggers\/#triggers-hasCountryFlag"/);
assert.match(countryHtml, /overflow-x-auto"><table/);
assert.match(armyHtml, /generates no event kind whose body runs in this scope/);
