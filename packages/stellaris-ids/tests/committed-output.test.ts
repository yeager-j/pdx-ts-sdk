/**
 * The committed identifier package, measured against the install it claims to
 * describe (SDK-12 seam D).
 *
 * `packages/stellaris-ids/src` is generated output that CI can never
 * reproduce — CI has no copy of Stellaris. So the trust story is committed
 * bytes plus this gate: next to a real install, regenerate the whole package in
 * memory and string-compare every file, both directions. `npm run
 * codegen:vanilla:check` does the same thing through git; this does it inside
 * the test suite, where a failure names the file.
 *
 * `formatEmitted` is deliberately in the loop. `generateVanillaPackage` returns
 * unformatted text by design, and Prettier decides the committed bytes, so
 * comparing raw emission against the tree would fail on formatting alone.
 */

import { readdirSync, readFileSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { formatEmitted } from "@pdx-ts/codegen-vanilla/format";
import { generateVanillaPackage } from "@pdx-ts/codegen-vanilla/generate";
import { locateInstall, requireGameVersion } from "@pdx-ts/sdk/stellaris";
import { describe, expect, it } from "vitest";

/** The repo root, from this module — never the directory vitest was started in. */
const ROOT = fileURLToPath(new URL("../../../", import.meta.url));
const PACKAGE = fileURLToPath(new URL("../", import.meta.url));
const OUT = path.join(PACKAGE, "src");
const CONFIG = path.join(ROOT, "vendor/cwtools-stellaris-config/config");
const DOCS = path.join(ROOT, "vendor/cwtools-stellaris-config/script-docs/v4.4.1");

let installRoot: string | undefined;
try {
  installRoot = locateInstall();
} catch {
  installRoot = undefined;
}

const manifest = JSON.parse(readFileSync(path.join(PACKAGE, "package.json"), "utf8")) as {
  version: string;
};

/**
 * The game build the package describes: its version minus the `-r.<n>`
 * revision counting publishes of that build (PROVENANCE.md, "Revisions"). What
 * the generator stamps into every file header is the *build*, so a revision
 * bump must not rewrite generated bytes — and the package version is never an
 * install version to compare against one.
 */
const packageGameVersion = manifest.version.split(/[-+]/, 1)[0]!;

/** The install's own statement of its build, as `major.minor.patch`. */
const installGameVersion = requireGameVersion;

function committedFiles(dir: string, prefix = ""): string[] {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const full = path.join(dir, name);
      return statSync(full).isDirectory()
        ? committedFiles(full, `${prefix}${name}/`)
        : [`${prefix}${name}`];
    });
}

const regenerated =
  installRoot === undefined
    ? undefined
    : await formatEmitted(
        generateVanillaPackage({
          installRoot,
          gameVersion: packageGameVersion,
          configRoot: CONFIG,
          docsRoot: DOCS,
        }).files,
        OUT
      );

describe.skipIf(installRoot === undefined)("committed vanilla package", () => {
  it("pins the package version to the installed game version", () => {
    expect(installGameVersion(installRoot!)).toBe(packageGameVersion);
  });

  it("carries a revision, so the package can be published more than once", () => {
    // A bare game version is a number npm has already consumed for this
    // package and can never reissue, so a stamp without a revision is one that
    // cannot be published at all (PROVENANCE.md, "Revisions").
    expect(manifest.version).toMatch(/^\d+\.\d+\.\d+-r\.\d+$/);
  });

  it("emits exactly the committed file set", () => {
    expect([...regenerated!.keys()].sort()).toEqual(committedFiles(OUT).sort());
  });

  it("emits byte-identical contents for every committed file", () => {
    for (const [name, text] of regenerated!) {
      expect(readFileSync(path.join(OUT, name), "utf8"), name).toBe(text);
    }
  });
});
